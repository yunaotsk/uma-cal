"""Compare Cal, A0, A, B, C: family (both rule sets), order, atom count, similarity-to-Cal.

Reads data/splits/*.csv and data/processed/meta.pkl (for n_elements); writes
data/splits/split_comparison.json and reports/split_comparison.md. No UMA inference.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd
from scipy import stats

from src import dataset as D

NAMES = ["cal", "A0", "A", "B", "C"]
sp = {n: pd.read_csv(ROOT / f"data/splits/{n}.csv") for n in NAMES}
for n, d in sp.items():
    d["n_elements"] = d.elements.str.split().map(len)
    d["order"] = d.n_elements.map(D.order_name)
    d["family_alt"] = d.elements.map(lambda s: D.family_alternative(s.split()))
cal_els = {e for s in sp["cal"].elements for e in s.split()}


def mix(col, order=None):
    t = pd.DataFrame({n: sp[n][col].value_counts(normalize=True) for n in NAMES}).fillna(0.0)
    return t.loc[order] if order else t.sort_values("cal", ascending=False)


def chi2_vs_cal(col, name):
    a, b = sp["cal"][col].value_counts(), sp[name][col].value_counts()
    cats = sorted(set(a.index) | set(b.index))
    tab = np.array([[a.get(c, 0), b.get(c, 0)] for c in cats])
    keep = tab.min(axis=1) >= 5  # pool sparse categories so the test is valid
    if (~keep).any():
        tab = np.vstack([tab[keep], tab[~keep].sum(axis=0)])
    chi2, p, dof, _ = stats.chi2_contingency(tab)
    return {"chi2": round(float(chi2), 2), "dof": int(dof), "p": round(float(p), 4)}


rows = {}
for n, d in sp.items():
    rows[n] = {
        "n": len(d),
        "natoms": {"mean": round(d.natoms.mean(), 2), "median": float(d.natoms.median()),
                   "p25": float(d.natoms.quantile(.25)), "p75": float(d.natoms.quantile(.75)),
                   "p95": float(d.natoms.quantile(.95)), "max": int(d.natoms.max())},
        "frac_natoms_le16": round(float((d.natoms <= 16).mean()), 3),
        "similarity_to_cal": {"mean": round(d.max_jaccard_to_cal.mean(), 3), "median": round(d.max_jaccard_to_cal.median(), 3),
                              "frac_eq_1": round(float((d.max_jaccard_to_cal == 1).mean()), 3),
                              "frac_ge_0.5": round(float((d.max_jaccard_to_cal >= .5).mean()), 3)},
        "frac_system_in_cal": round(float(d.elements.isin(set(sp["cal"].elements)).mean()), 3) if n != "cal" else 1.0,
        "frac_with_element_not_in_cal": round(float(d.elements.map(lambda s: bool(set(s.split()) - cal_els)).mean()), 3),
        "frac_3d_or_4d_tm": round(float((d.tm_class != "neither").mean()), 3),
    }
a0 = {
    "family_chi2": chi2_vs_cal("family", "A0"),
    "family_alt_chi2": chi2_vs_cal("family_alt", "A0"),
    "order_chi2": chi2_vs_cal("order", "A0"),
    "natoms_ks": {k: round(float(v), 4) for k, v in zip(("stat", "p"), stats.ks_2samp(sp["cal"].natoms, sp["A0"].natoms))},
    "similarity_ks": {k: round(float(v), 4) for k, v in zip(("stat", "p"), stats.ks_2samp(sp["cal"].max_jaccard_to_cal, sp["A0"].max_jaccard_to_cal))},
    "max_abs_family_share_diff": round(float((mix("family")["cal"] - mix("family")["A0"]).abs().max()), 4),
    "max_abs_order_share_diff": round(float((mix("order")["cal"] - mix("order")["A0"]).abs().max()), 4),
}
out = {"per_split": rows, "A0_vs_cal": a0}
(ROOT / "data/splits/split_comparison.json").write_text(json.dumps(out, indent=2))


def md_table(df, fmt="{:.1%}"):
    head = "| | " + " | ".join(df.columns) + " |\n|---|" + "---:|" * len(df.columns) + "\n"
    return head + "\n".join(f"| {i} | " + " | ".join(fmt.format(v) for v in r) + " |" for i, r in df.iterrows()) + "\n"


L = ["# Split comparison (Cal, A0, A, B, C)", "",
     "Generated by `scripts/compare_splits.py` from `data/splits/*.csv` (no UMA inference). One structure per composition in every split.", "",
     "| Split | n | median atoms (mean) | p95 atoms | share <=16 atoms | mean / median similarity to Cal | share with system in Cal | share with element not in Cal |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
for n in NAMES:
    r = rows[n]
    L.append(f"| {n} | {r['n']:,} | {r['natoms']['median']:.0f} ({r['natoms']['mean']}) | {r['natoms']['p95']:.0f} | {r['frac_natoms_le16']:.1%} | "
             f"{r['similarity_to_cal']['mean']} / {r['similarity_to_cal']['median']} | {r['frac_system_in_cal']:.1%} | {r['frac_with_element_not_in_cal']:.1%} |")
L += ["", "Similarity = max Jaccard similarity between a structure's element set and any Cal element set. For Cal itself it is leave-one-composition-out (other Cal compositions only).", "",
      "## Composition order", "", md_table(mix("order", ["binary", "ternary", "quaternary+"])),
      "## Family mix (rules used in the splits)", "", md_table(mix("family")),
      "## Family mix (alternative rules: H/C/N/P/As count as anions; B/Si/Ge/Sb merged)", "", md_table(mix("family_alt")),
      "## A0 versus Cal (A0 should look like Cal)", "",
      f"- Family (used rules): chi-square {a0['family_chi2']}; alternative rules: {a0['family_alt_chi2']}; order: {a0['order_chi2']}.",
      f"- Atom count KS: {a0['natoms_ks']}; similarity-to-Cal KS: {a0['similarity_ks']}.",
      f"- Largest absolute difference in a family share: {a0['max_abs_family_share_diff']:.1%}; in an order share: {a0['max_abs_order_share_diff']:.1%}.",
      "- Cal and A0 are two draws from one random split of the same pool, so differences are sampling noise by construction. A small p-value would indicate a bug, not a real shift (about 1 in 20 tests will fall below 0.05 by chance).", "",
      "## Reading the other splits", "",
      "- **A** is restricted to systems that also occur in Cal (similarity 1.0 by construction) and is drawn from the leftover pool, so its mix reflects multi-composition systems.",
      "- **B** has no system in Cal by construction, but shares pairs and elements with Cal. **C** contains f-block elements absent from Cal and differs in order and family mix; see `reports/analysis_plan.md` for the matched comparison.", ""]
(ROOT / "reports/split_comparison.md").write_text("\n".join(L))
print(json.dumps(out["A0_vs_cal"], indent=1))
